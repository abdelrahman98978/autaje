function applyTranslations(lang) {
  const dictionary = translations[lang] || translations["ar"];
  
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dictionary[key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = dictionary[key];
      } else {
        // Preserving Material Symbols if present
        const icon = el.querySelector(".material-symbols-outlined");
        if (icon) {
          const iconText = icon.textContent;
          el.innerHTML = "";
          el.appendChild(icon);
          el.appendChild(document.createTextNode(" " + dictionary[key]));
        } else {
          el.textContent = dictionary[key];
        }
      }
    }
  });

  // Special handling for the language toggle text
  const langToggle = document.getElementById("langToggle");
  if (langToggle) {
    const langNames = { "ar": "العربية", "en": "English", "fr": "Français", "es": "Español" };
    langToggle.innerHTML = `${langNames[lang] || "Language"} <span class="material-symbols-outlined" style="font-size: 16px; vertical-align: middle;">language</span>`;
  }
}

// Export for use in main.js
window.applyTranslations = applyTranslations;
